from enum import Enum


class SufficiencyVerdict(str, Enum):
    SUFFICIENT = "SUFFICIENT"
    PARTIALLY_SUFFICIENT = "PARTIALLY_SUFFICIENT"
    INSUFFICIENT = "INSUFFICIENT"


class SignalName(str, Enum):
    TERM_COVERAGE = "TERM_COVERAGE"
    SUBQUERY_COVERAGE = "SUBQUERY_COVERAGE"
    EVIDENCE_QUANTITY = "EVIDENCE_QUANTITY"
    SOURCE_DIVERSITY = "SOURCE_DIVERSITY"
    CONTENT_ADEQUACY = "CONTENT_ADEQUACY"
    RETRIEVAL_CONSENSUS = "RETRIEVAL_CONSENSUS"
    EXECUTION_HEALTH = "EXECUTION_HEALTH"
    EVIDENCE_CONFLICT = "EVIDENCE_CONFLICT"


class GapType(str, Enum):
    NO_EVIDENCE = "NO_EVIDENCE"
    EXECUTION_DEGRADED = "EXECUTION_DEGRADED"
    SUBQUERY_UNCOVERED = "SUBQUERY_UNCOVERED"
    LOW_TERM_COVERAGE = "LOW_TERM_COVERAGE"
    TOO_FEW_EVIDENCE = "TOO_FEW_EVIDENCE"
    LOW_SOURCE_DIVERSITY = "LOW_SOURCE_DIVERSITY"
    LOW_CONTENT = "LOW_CONTENT"
    WEAK_AGREEMENT = "WEAK_AGREEMENT"
    CONFLICT_UNRESOLVED = "CONFLICT_UNRESOLVED"


class GapSeverity(str, Enum):
    HARD = "HARD"   # caps the verdict at PARTIALLY_SUFFICIENT
    SOFT = "SOFT"   # lowers the score only


class EscalationAction(str, Enum):
    WIDEN_DEPTH = "WIDEN_DEPTH"                # same query, bigger top_k
    TARGET_SUBQUERIES = "TARGET_SUBQUERIES"    # one step per uncovered sub-question
    GAP_FOCUSED_QUERY = "GAP_FOCUSED_QUERY"    # query built from the uncovered terms
    KEYWORD_REWRITE = "KEYWORD_REWRITE"        # filler words removed, keywords only
    SPLIT_RETRIEVERS = "SPLIT_RETRIEVERS"      # semantic and lexical as separate steps


class StopReason(str, Enum):
    SUFFICIENT = "SUFFICIENT"
    MAX_ROUNDS_REACHED = "MAX_ROUNDS_REACHED"
    DEADLINE_EXCEEDED = "DEADLINE_EXCEEDED"
    NO_PROGRESS = "NO_PROGRESS"
    NO_ESCALATION_AVAILABLE = "NO_ESCALATION_AVAILABLE"
    ESCALATION_REJECTED = "ESCALATION_REJECTED"
    EXECUTION_ERROR = "EXECUTION_ERROR"
    NO_SEARCHABLE_DOCUMENTS = "NO_SEARCHABLE_DOCUMENTS"
